export const translations: Record<SupportedLanguage, TranslationMap> = {
  en,
  fr,
  ar,
  adlam,
};

export const t = (language: SupportedLanguage, key: string): string => {
  return translations[language]?.[key] ?? translations.en[key] ?? key;
};

export const getGreetingKey = (hour: number): string => {
  if (hour < 5) return 'greeting.night';
  if (hour < 12) return 'greeting.morning';
  if (hour < 17) return 'greeting.afternoon';
  if (hour < 21) return 'greeting.evening';
  return 'greeting.night';
};

export const isRtlLanguage = (language: SupportedLanguage): boolean => {
  return language === 'ar' || language === 'adlam';
};

export const getLocale = (language: SupportedLanguage): string => {
  if (language === 'fr') return 'fr';
  if (language === 'ar') return 'ar';
  return 'en';
};
